    public const string Source = "SAE J2012 genérico, traducción TallerScan rev. 1";

    public static DtcInfo Describe(string code)
    {
        code = code.ToUpperInvariant();
        string system = DtcCodec.IsValid(code) ? DtcCodec.SystemName(code) : "Desconocido";
        bool generic = DtcCodec.IsValid(code) && DtcCodec.IsGeneric(code);
        if (Generic.TryGetValue(code, out var text))
            return new DtcInfo(code, text, system, true, Source);
        // P0301 a P0312: falla de encendido en el cilindro indicado.
        if (code.Length == 5 && code.StartsWith("P03", StringComparison.Ordinal)
            && int.TryParse(code[3..], out int cyl) && cyl is >= 1 and <= 12)
            return new DtcInfo(code, $"Falla de encendido detectada en el cilindro {cyl}", system, true, Source);
        return new DtcInfo(code, null, system, generic, generic ? Source : "Código del fabricante");
    }

