public sealed record DtcInfo(string Code, string? Description, string System, bool IsGeneric, string Source);

// Descripciones de códigos genéricos (SAE J2012 / ISO 15031-6), traducción propia.
// Solo genéricos: un P1xxx significa cosas distintas en cada marca, así que se
// muestra "descripción no disponible" en vez de inventar.
